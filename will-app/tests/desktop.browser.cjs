async function launch(profile) {
  const app = await _electron.launch({
    executablePath, args: packaged ? [] : [root],
    env: { ...process.env, WILL_USER_DATA_DIR: profile, WILL_DEV_SERVER_URL: '' },
    timeout: 30000,
  })
  openApps.add(app)
  app.process().stderr.on('data', chunk => { void fs.appendFile(path.join(run, 'electron-stderr.log'), chunk) })
  app.process().on('exit', (code, signal) => console.log(`Electron exited: ${code}, ${signal || 'no signal'}`))
  const page = await app.firstWindow()
  page.setDefaultTimeout(10000)
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (!/^(will:|data:|devtools:)/.test(request.url())) requests.push(request.url())
  })
  await page.clock.setFixedTime(now)
  await page.getByRole('heading', { name: '我的工作台', exact: true }).waitFor()
  await app.context().setOffline(true)
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: '我的工作台', exact: true }).waitFor()
  metadata = await app.evaluate(({ app, BrowserWindow }) => ({
    isPackaged: app.isPackaged, version: app.getVersion(), versions: process.versions,
    userData: app.getPath('userData'), bounds: BrowserWindow.getAllWindows()[0].getBounds(),
    preferences: BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences(),
  }))
  assert.equal(metadata.isPackaged, packaged)
  assert.equal(page.url(), 'will://app/')
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined')
  assert.equal(await page.evaluate(() => isSecureContext && typeof crypto.randomUUID === 'function'), true)
  return { app, page }
}
async function close(app) { await app.close(); openApps.delete(app) }
const navigate = (page, name) => page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
const stored = page => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)
const raw = page => page.evaluate(key => localStorage.getItem(key), key)
const dialog = page => page.getByRole('dialog').filter({ visible: true }).last()
async function capture(page, name) {
  await page.mouse.move(0, 0)
  await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); window.scrollTo(0, 0) })
  await page.waitForTimeout(250)
  await page.screenshot({ path: path.join(evidence, 'images', `${name}.png`), animations: 'disabled', scale: 'css' })
  screenshots.push(`${name}.png`)
}
async function generate(page, text) {
  await page.getByRole('textbox', { name: '输入安排', exact: true }).fill(text)
  await page.getByRole('button', { name: '生成草案', exact: true }).click()
}
async function select(group, page, label, option) {
  await group.getByLabel(label, { exact: true }).click()
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option').filter({ hasText: option }).click()
}

